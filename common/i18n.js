// t('key') 或 t('key', {a: 1}) 模板插值
window.t = function (key, vars) {
  let s = (window.PAXI_I18N[window.PAXI_LANG] && window.PAXI_I18N[window.PAXI_LANG][key]);
  if (s === undefined) s = window.PAXI_I18N.zh[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
};
window.setLang = function (lang) {
  localStorage.setItem('paxi_lang', lang);
  window.location.reload();
};
